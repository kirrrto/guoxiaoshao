// Build display labels from the same source as the mainland picker. No network requests.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const products = require('../../catalog/products.json').products;
const attributes = require('../i18n/source/catalog-attributes');
const chinese = /[\u3400-\u9fff]/;
const normalize = value => value.replace(/\s+/g, ' ').trim();
const phrases = Object.entries(attributes).filter(([key]) => !key.includes('{')).sort((a,b) => b[0].length - a[0].length);
function label(source) {
  let value = source
    .replace(/(MacBook Pro \(PROLED XDR 显示屏\)|MacBook Air|MacBook Pro|iPad Air|iPad Pro) (\d+) 英寸/g, '$2-inch $1')
    .replace(/(\d+)核CPU\/(\d+)核GPU/g, '$1-core CPU/$2-core GPU')
    .replace(/(\d+(\.\d+)?) 英寸/g, '$1-inch');
  for (const [key,en] of phrases) value = value.replaceAll(key,en);
  if (chinese.test(value)) throw Error('Missing catalog descriptor: '+source);
  return value;
}
export function buildCatalogNames() {
  const names = new Map();
  const add = (key,en) => {
    if (!key || !chinese.test(key)) return;
    if (names.has(key) && names.get(key)!==en) throw Error('Ambiguous catalog label: '+key);
    names.set(key,en);
  };
  for (const p of products) {
    const title = normalize(p.title);
    // Apple's short English Mac marketing names omit the chip, RAM and storage. Preserve the SKU.
    const official = p.englishName && normalize(p.englishName);
    const colorName = attributes[p.attributes.color];
    const finishMatches = !colorName || official?.toLowerCase().includes(colorName.toLowerCase());
    add(title, p.category !== 'mac' && official && finishMatches ? official : label(title));
    add(p.model, label(p.model));
    if (title.startsWith(p.model + ' ')) {
      const configuration = title.slice(p.model.length).trim();
      // Some one-attribute configurations are also independent picker options.
      if (!Object.hasOwn(attributes, configuration)) add(configuration, label(configuration));
    }
    const color = p.attributes.color;
    if (color && title.endsWith(' '+color)) {
      const modelAndConfiguration = title.slice(0, -color.length).trim();
      add(modelAndConfiguration, label(modelAndConfiguration));
    }
    for (const field of ['screensize','chip','finish','connection','charging']) {
      const a = p.attributes[field];
      if (a && !Object.hasOwn(attributes,a)) add(a,label(a));
    }
  }
  return Object.fromEntries(names);
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const names = buildCatalogNames();
  const path = fileURLToPath(new URL('../i18n/source/catalog-titles.js',import.meta.url));
  const source = '// Generated by tools/catalog/build-english-names.mjs from checked-in Apple product data.\nmodule.exports = '+JSON.stringify(names,null,2)+';\n';
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(path,'utf8') !== source) throw Error('Rebuild bundled catalog labels with node tools/catalog/build-english-names.mjs');
  } else fs.writeFileSync(path,source);
}
